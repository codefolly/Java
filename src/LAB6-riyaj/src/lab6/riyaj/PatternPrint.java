package lab6.riyaj;


public class PatternPrint {

    
    public static void main(String[] args) {
        String a="HETAUDA";
        for(int i=0;i<4;i++){
            for(int j=0+i;j<7-i;j++){
                System.out.print(a.charAt(j));
                
                
            }
            System.out.println("");
        }
       
    }
    
}
